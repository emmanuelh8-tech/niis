// niis/report.js: ICT reports written by NIIS from its published figures. Four kinds: an indicator brief, a
// county profile, a thematic (domain) report and the annual summary. Each is an HTML article saved with the
// report, so a published report never changes when the data later does: a new edition is a new report.
// Every sentence with a number in it comes from niis/analytics.js; nothing is written by hand.
'use strict';
const A = require('./analytics');

const esc = (s) => String(s == null ? '' : s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const isDemo = (rows) => rows.some((r) => /mock data|demonstration data/i.test(String(r.source || '')));
const today = () => new Date().toISOString().slice(0, 10);
const KINDS = {
  indicator: { tag: 'Indicator Brief', label: 'Indicator brief', hint: 'One indicator: its trend, its counties and what they show' },
  county: { tag: 'County Profile', label: 'County profile', hint: 'One county against the national figure, indicator by indicator' },
  domain: { tag: 'Thematic Report', label: 'Thematic report', hint: 'Every indicator in one of the 17 domains' },
  annual: { tag: 'Annual Summary', label: 'Annual summary', hint: 'The year across all domains: levels, movers and coverage' },
};

function cover({ kind, title, year, demo, lede }) {
  return `<header class="rpt-cover">
    <p class="rpt-kicker">NIIS · ${esc(KINDS[kind].tag)} · ${esc(String(year))}</p>
    <h1>${esc(title)}</h1>
    ${lede ? `<p class="rpt-lede">${esc(lede)}</p>` : ''}
    <p class="rpt-meta">National ICT Intelligence System (NIIS), National ICT Intelligence Program · Generated ${today()} from published figures</p>
    ${demo ? '<p class="rpt-demo" role="note"><strong>Demonstration data.</strong> The figures in this report come from NIIS\'s demonstration dataset. They are not official statistics.</p>' : ''}
  </header>`;
}
const keys = (items) => `<section class="rpt-keys">${items.map((k) => `<div class="rpt-key"><span class="rpt-key-v">${esc(k.v)}</span><span class="rpt-key-l">${esc(k.l)}</span></div>`).join('')}</section>`;
const list = (xs) => `<ul class="rpt-findings">${xs.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>`;
const footer = () => `<footer class="rpt-foot">Generated by NIIS on ${today()} from the figures published in the NIIS data store. Every value traces to its data point, its source and the checks it passed. Cite as: National ICT Intelligence Program, NIIS.</footer>`;

// ---- an indicator brief
function indicatorBrief({ ind, year, series, counties, domainLabel }) {
  const nat = series.find((s) => s.year === year);
  const st = A.seriesStats(series.filter((s) => s.year <= year));
  const ds = A.distStats(counties, nat ? nat.value : null);
  const demo = isDemo(series) || isDemo(counties);
  const f = A.findings({ ind, series: series.filter((s) => s.year <= year), counties, year, demo: false });
  const title = `${ind.name}: ${year}`;
  const body = `<article class="rpt">
  ${cover({ kind: 'indicator', title, year, demo, lede: ind.description })}
  ${keys([
    { v: nat ? A.fmtVal(nat.value, ind.unit) : 'no data', l: `Liberia, ${year} (${ind.unit})` },
    ...(st && st.n > 1 ? [{ v: A.fmtChange(st.change, ind.unit), l: `Since ${st.first.year}` }] : []),
    ...(ds ? [{ v: A.fmtVal(ds.best.value, ind.unit), l: `Highest county: ${ds.best.county}` }, { v: `${ds.n} of 15`, l: 'Counties with a figure' }] : []),
  ])}
  <section><h2>Key findings</h2>${list(f)}</section>
  ${series.length > 1 ? `<section><h2>The national trend</h2>${A.svgLine(series.filter((s) => s.year <= year), { unit: ind.unit, label: ind.name })}</section>` : ''}
  ${counties.length ? `<section><h2>By county, ${year}</h2>${A.svgBars(counties, { unit: ind.unit, national: nat ? nat.value : null, label: ind.name + ' by county' })}
  <table class="rpt-table"><thead><tr><th>County</th><th class="num">${esc(ind.unit)}</th><th class="num">Against Liberia</th></tr></thead><tbody>
  ${ds.sorted.map((c) => `<tr><td>${esc(c.county)}</td><td class="num">${esc(A.fmtVal(c.value, ind.unit))}</td><td class="num">${nat ? esc(A.fmtChange(c.value - nat.value, ind.unit)) : ''}</td></tr>`).join('')}
  </tbody></table></section>` : ''}
  <section><h2>Definition and method</h2>
    <dl class="rpt-dl"><div><dt>Definition</dt><dd>${esc(ind.description || 'Not recorded.')}</dd></div>
    <div><dt>Unit</dt><dd>${esc(ind.unit)}</dd></div>
    <div><dt>Domain</dt><dd>${esc(domainLabel || ind.domain)}</dd></div>
    <div><dt>Frequency</dt><dd>${esc(ind.periodicity || 'Annual')}</dd></div>
    ${ind.methodology ? `<div><dt>Method</dt><dd>${esc(ind.methodology)}</dd></div>` : ''}</dl>
  </section>
  ${footer()}
</article>`;
  return { title, tag: KINDS.indicator.tag, period: String(year), summary: f.slice(0, 2).join(' '), body, demo };
}

// ---- a county profile: the county beside Liberia, indicator by indicator, grouped by domain
function countyProfile({ county, year, rows, domainLabels, domainOrder }) {
  // rows: [{ ind, value, national, prev, source }]
  const demo = isDemo(rows);
  const have = rows.filter((r) => r.value != null);
  const comparable = have.filter((r) => r.national != null && r.national !== 0);
  const rel = comparable.map((r) => ({ ...r, gap: (r.value - r.national) / Math.abs(r.national) }));
  const ahead = rel.filter((r) => r.gap > 0.05).sort((a, b) => b.gap - a.gap);
  const behind = rel.filter((r) => r.gap < -0.05).sort((a, b) => a.gap - b.gap);
  const f = [];
  f.push(`${county} has a figure for ${have.length} of the ${rows.length} NIIS indicators in ${year}.`);
  if (comparable.length) f.push(`It is above the national figure on ${rel.filter((r) => r.gap > 0).length} of ${comparable.length} indicators that have both a county and a national figure.`);
  if (ahead[0]) f.push(`Furthest ahead: ${ahead[0].ind.name}, ${A.fmtVal(ahead[0].value, ahead[0].ind.unit)} against ${A.fmtVal(ahead[0].national, ahead[0].ind.unit)} for Liberia.`);
  if (behind[0]) f.push(`Furthest behind: ${behind[0].ind.name}, ${A.fmtVal(behind[0].value, behind[0].ind.unit)} against ${A.fmtVal(behind[0].national, behind[0].ind.unit)} for Liberia.`);
  const byDom = {};
  have.forEach((r) => (byDom[r.ind.domain] = byDom[r.ind.domain] || []).push(r));
  const title = `${county} County ICT Profile ${year}`;
  const body = `<article class="rpt">
  ${cover({ kind: 'county', title, year, demo, lede: `How ${county} County compares with Liberia as a whole on the national ICT indicators.` })}
  ${keys([{ v: String(have.length), l: 'Indicators with a figure' }, { v: String(rel.filter((r) => r.gap > 0).length), l: 'Above the national figure' }, { v: String(rel.filter((r) => r.gap < 0).length), l: 'Below the national figure' }])}
  <section><h2>Key findings</h2>${list(f)}</section>
  ${ahead.length ? `<section><h2>Where ${esc(county)} leads</h2><table class="rpt-table"><thead><tr><th>Indicator</th><th class="num">${esc(county)}</th><th class="num">Liberia</th></tr></thead><tbody>
    ${ahead.slice(0, 8).map((r) => `<tr><td>${esc(r.ind.name)}</td><td class="num">${esc(A.fmtVal(r.value, r.ind.unit))}</td><td class="num">${esc(A.fmtVal(r.national, r.ind.unit))}</td></tr>`).join('')}</tbody></table></section>` : ''}
  ${behind.length ? `<section><h2>Where ${esc(county)} trails</h2><table class="rpt-table"><thead><tr><th>Indicator</th><th class="num">${esc(county)}</th><th class="num">Liberia</th></tr></thead><tbody>
    ${behind.slice(0, 8).map((r) => `<tr><td>${esc(r.ind.name)}</td><td class="num">${esc(A.fmtVal(r.value, r.ind.unit))}</td><td class="num">${esc(A.fmtVal(r.national, r.ind.unit))}</td></tr>`).join('')}</tbody></table></section>` : ''}
  <section><h2>Every indicator, by domain</h2>
  ${domainOrder.filter((d) => byDom[d]).map((d) => `<h3>${esc(domainLabels[d] || d)}</h3><table class="rpt-table"><thead><tr><th>Indicator</th><th>Unit</th><th class="num">${esc(county)}</th><th class="num">Liberia</th><th class="num">Change on ${year - 1}</th></tr></thead><tbody>
    ${byDom[d].map((r) => `<tr><td>${esc(r.ind.name)}</td><td class="muted">${esc(r.ind.unit)}</td><td class="num">${esc(A.fmtVal(r.value, r.ind.unit))}</td><td class="num">${esc(A.fmtVal(r.national, r.ind.unit))}</td><td class="num">${r.prev != null ? esc(A.fmtChange(r.value - r.prev, r.ind.unit)) : ''}</td></tr>`).join('')}
  </tbody></table>`).join('')}
  </section>
  ${footer()}
</article>`;
  return { title, tag: KINDS.county.tag, period: String(year), summary: f.slice(0, 2).join(' '), body, demo };
}

// ---- a thematic report: one domain
function domainReport({ domain, label, year, items }) {
  // items: [{ ind, series, counties: number of counties with a figure in year }]
  const demo = items.some((it) => isDemo(it.series));
  const rows = items.map((it) => {
    const s = it.series.filter((x) => x.year <= year);
    const st = A.seriesStats(s);
    const cur = s.find((x) => x.year === year);
    return { ...it, s, st, cur };
  });
  const withData = rows.filter((r) => r.cur);
  const up = withData.filter((r) => r.st && r.st.prev && r.st.yoy > 0).length, down = withData.filter((r) => r.st && r.st.prev && r.st.yoy < 0).length;
  const f = [`${withData.length} of the ${items.length} ${label} indicators have a national figure for ${year}.`];
  if (up + down) f.push(`Over the last year ${up} rose and ${down} fell.`);
  const movers = withData.filter((r) => r.st && r.st.prev && r.st.prev.value).map((r) => ({ r, rel: r.st.yoy / Math.abs(r.st.prev.value) })).sort((a, b) => Math.abs(b.rel) - Math.abs(a.rel));
  if (movers[0]) f.push(`The largest movement: ${movers[0].r.ind.name}, ${A.fmtChange(movers[0].r.st.yoy, movers[0].r.ind.unit)} (${movers[0].rel > 0 ? '+' : ''}${Math.round(movers[0].rel * 100)}%).`);
  const title = `${label}: ${year}`;
  const body = `<article class="rpt">
  ${cover({ kind: 'domain', title, year, demo, lede: `The ${label.toLowerCase()} indicators of the national framework, their latest national figures and how they have moved.` })}
  ${keys([{ v: String(items.length), l: 'Indicators in the domain' }, { v: String(withData.length), l: `With a figure for ${year}` }, { v: `${up} / ${down}`, l: 'Rose / fell on the year' }])}
  <section><h2>Key findings</h2>${list(f)}</section>
  <section><h2>The indicators</h2><table class="rpt-table"><thead><tr><th>Indicator</th><th>Unit</th><th class="num">${year}</th><th class="num">On the year</th><th class="num">Counties</th><th>Trend</th></tr></thead><tbody>
  ${rows.map((r) => `<tr><td>${esc(r.ind.name)}</td><td class="muted">${esc(r.ind.unit)}</td><td class="num">${r.cur ? esc(A.fmtVal(r.cur.value, r.ind.unit)) : 'no data'}</td><td class="num">${r.st && r.st.prev && r.cur ? esc(A.fmtChange(r.st.yoy, r.ind.unit)) : ''}</td><td class="num">${r.counties || 0}</td><td>${A.svgSpark(r.s)}</td></tr>`).join('')}
  </tbody></table></section>
  ${withData.slice(0, 4).map((r) => `<section><h2>${esc(r.ind.name)}</h2>${list(A.findings({ ind: r.ind, series: r.s, counties: [], year }).slice(0, 3))}${r.s.length > 1 ? A.svgLine(r.s, { unit: r.ind.unit, label: r.ind.name, h: 220 }) : ''}</section>`).join('')}
  ${footer()}
</article>`;
  return { title, tag: KINDS.domain.tag, period: String(year), summary: f.slice(0, 2).join(' '), body, demo };
}

// ---- the annual summary: every domain in one view
function annualSummary({ year, domains, coverage }) {
  // domains: [{ label, items: [{ ind, cur, prev }] }]; coverage: { indicators, withData, counties }
  const all = domains.flatMap((d) => d.items);
  const demo = all.some((it) => /mock data|demonstration data/i.test(String(it.source || '')));
  const withData = all.filter((x) => x.cur != null);
  const moved = withData.filter((x) => x.prev != null && x.prev !== 0).map((x) => ({ ...x, rel: (x.cur - x.prev) / Math.abs(x.prev) }));
  const rising = moved.filter((x) => x.rel > 0).sort((a, b) => b.rel - a.rel);
  const falling = moved.filter((x) => x.rel < 0).sort((a, b) => a.rel - b.rel);
  const f = [`NIIS holds a national figure for ${withData.length} of its ${all.length} indicators in ${year}.`,
    `${rising.length} indicators rose on ${year - 1} and ${falling.length} fell.`];
  if (rising[0]) f.push(`Strongest rise: ${rising[0].ind.name} (${Math.round(rising[0].rel * 100)}%).`);
  if (falling[0]) f.push(`Largest fall: ${falling[0].ind.name} (${Math.round(falling[0].rel * 100)}%).`);
  const title = `Liberia ICT Statistics ${year}: Annual Summary`;
  const body = `<article class="rpt">
  ${cover({ kind: 'annual', title, year, demo, lede: `The year in Liberia's national ICT indicators: ${domains.length} domains, their latest figures and the year's movements.` })}
  ${keys([{ v: String(withData.length), l: `Indicators with a ${year} figure` }, { v: String(rising.length), l: 'Rose on the year' }, { v: String(falling.length), l: 'Fell on the year' }, { v: String(coverage.counties || 0), l: 'Counties reporting' }])}
  <section><h2>Key findings</h2>${list(f)}</section>
  ${rising.length ? `<section><h2>The biggest movers</h2><table class="rpt-table"><thead><tr><th>Indicator</th><th class="num">${year - 1}</th><th class="num">${year}</th><th class="num">Change</th></tr></thead><tbody>
    ${rising.slice(0, 5).concat(falling.slice(0, 5)).map((x) => `<tr><td>${esc(x.ind.name)}</td><td class="num">${esc(A.fmtVal(x.prev, x.ind.unit))}</td><td class="num">${esc(A.fmtVal(x.cur, x.ind.unit))}</td><td class="num">${x.rel > 0 ? '+' : ''}${Math.round(x.rel * 100)}%</td></tr>`).join('')}</tbody></table></section>` : ''}
  ${domains.map((d) => `<section><h2>${esc(d.label)}</h2><table class="rpt-table"><thead><tr><th>Indicator</th><th>Unit</th><th class="num">${year}</th><th class="num">On ${year - 1}</th></tr></thead><tbody>
    ${d.items.map((x) => `<tr><td>${esc(x.ind.name)}</td><td class="muted">${esc(x.ind.unit)}</td><td class="num">${x.cur != null ? esc(A.fmtVal(x.cur, x.ind.unit)) : 'no data'}</td><td class="num">${x.cur != null && x.prev != null ? esc(A.fmtChange(x.cur - x.prev, x.ind.unit)) : ''}</td></tr>`).join('')}
  </tbody></table></section>`).join('')}
  ${footer()}
</article>`;
  return { title, tag: KINDS.annual.tag, period: String(year), summary: f.slice(0, 2).join(' '), body, demo };
}

module.exports = { KINDS, indicatorBrief, countyProfile, domainReport, annualSummary };
